/** Common GST rates in %, after the 2025 rate rationalisation (5% and 18% main slabs). */
export const GST_RATES = [0, 0.25, 3, 5, 18, 40] as const;

const GSTIN_PATTERN = /^\d{2}[A-Z]{5}\d{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/;

export function isValidGstin(gstin: string): boolean {
  return GSTIN_PATTERN.test(gstin.trim().toUpperCase());
}

/** The state code embedded in a GSTIN, if it is a known state. */
export function stateCodeFromGstin(gstin: string): string | null {
  const code = gstin.trim().slice(0, 2);
  return INDIAN_STATES.some((state) => state.code === code) ? code : null;
}

export function stateName(code: string): string | null {
  return INDIAN_STATES.find((state) => state.code === code)?.name ?? null;
}
